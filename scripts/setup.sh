#!/usr/bin/env bash
# One-time machine setup, no root needed. Reproduces the CMOS5L toolchain that
# TinyTapeout/tt-gds-action@ihp-cmos5l uses in CI:
#   - IHP-Open-PDK at the revision pinned by tt-gds-action/install_sg13cmos5l.sh
#   - LibreLane 3.1.0.dev3 + its OpenROAD/Yosys/Magic/Netgen/KLayout via nix-portable
#   - tt-support-tools (branch ihp-sg13cmos5l) in tools/tt
#   - a Python venv (tools/.venv) for tt-support-tools and cocotb
# Local simulators (iverilog, verilator, sby) are expected on PATH already.
set -euo pipefail
cd "$(dirname "$0")/.."

TTSETUP="$PWD/tools"
export XDG_CACHE_HOME="$TTSETUP/.cache" UV_PYTHON_INSTALL_DIR="$TTSETUP/python"
IHP_PDK_REV=2bbec755dc67ca3db0261c3d6163e15735d66710   # keep in sync with tt-gds-action@ihp-cmos5l
LIBRELANE_REV=ca6adb1e2982cd75445a68b632d461213d8ca421 # tag 3.1.0.dev3
NIX_PORTABLE_URL=https://github.com/DavHau/nix-portable/releases/download/v012/nix-portable-x86_64

mkdir -p "$TTSETUP/bin" "$TTSETUP/pdk"

cat > "$TTSETUP/np-env.sh" <<EOF
# Generated by scripts/setup.sh.
export NP_LOCATION="$TTSETUP"
export NP_RUNTIME=bwrap
export NIX_CONFIG='extra-substituters = https://nix-cache.fossi-foundation.org
extra-trusted-public-keys = nix-cache.fossi-foundation.org:3+K59iFwXqKsL7BNu6Guy0v+uTlwsxYQxjspXzqLYQs=
extra-experimental-features = nix-command flakes
accept-flake-config = true'
export PDK_ROOT="$TTSETUP/pdk"
export PDK=ihp-sg13cmos5l
export LIBRELANE_REF="github:librelane/librelane/$LIBRELANE_REV"
EOF

if [ ! -x "$TTSETUP/bin/nix-portable" ]; then
  curl -sSL -o "$TTSETUP/bin/nix-portable" "$NIX_PORTABLE_URL"
  chmod +x "$TTSETUP/bin/nix-portable"
fi

if [ ! -f "$TTSETUP/pdk/ihp-sg13cmos5l/SOURCES" ]; then
  git -C "$TTSETUP/pdk" init -q
  git -C "$TTSETUP/pdk" fetch -q --depth 1 https://github.com/IHP-GmbH/IHP-Open-PDK.git "$IHP_PDK_REV"
  git -C "$TTSETUP/pdk" checkout -q FETCH_HEAD
  echo "IHP-Open-PDK $IHP_PDK_REV" > "$TTSETUP/pdk/ihp-sg13cmos5l/SOURCES"
fi

# First call downloads ~6 GB of binaries from the FOSSi and NixOS caches.
(
  source "$TTSETUP/np-env.sh"
  "$TTSETUP/bin/nix-portable" nix develop "$LIBRELANE_REF" --command \
    bash -c 'openroad -version && yosys -V && python -c "import librelane; print(\"librelane\", librelane.__version__)"'
)

[ -d "$TTSETUP/tt" ] || git clone -q -b ihp-sg13cmos5l https://github.com/TinyTapeout/tt-support-tools "$TTSETUP/tt"

if [ ! -x "$TTSETUP/.venv/bin/python" ]; then
  uv venv -q --python 3.12 "$TTSETUP/.venv"
  uv pip install -q --python "$TTSETUP/.venv/bin/python" -r "$TTSETUP/tt/requirements.txt" -r simulator/test/requirements.txt pyyaml
fi
echo "setup complete"
