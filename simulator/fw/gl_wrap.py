"""Gate-level wrapper for the fw cocotb harness: `python -m fw.gl_wrap <netlist.nl.v> <out.v>`.

The hardened netlist is flat and has only the Tiny Tapeout ports, but `fw/rtl_harness.py` talks to the
chip's internal register bus (one bus access per core cycle).  This writes `gl_top`, a module with the
same ports as `pio_chip` (clk, rst_n, bus_*, pin_*, irq*) around `tt_um_protocol_emulator`:

  * the bus: `bus_we / bus_re / bus_addr / bus_wdata` are the netlist's own bus nets (the nets host_spi drives
    into the chip, kept by name through synthesis); gl_top `force`s them (re-forced on every change), so a bus access reaches the
    chip exactly as in the RTL, in one cycle.  host_spi is left idle (CSn low, SCK/MOSI low).
  * read data: the netlist has no `bus_rdata` net (it is folded into logic), but host_spi captures
    bus_rdata into `miso_sr_q` at the edge where `re_q` (= bus_re, forced) is high, so after a read cycle
    `bus_rdata` = miso_sr_q[31:0] is exactly the value the read returned (the RTL harness samples it
    just before the same edge).
  * pins: pin_in[7:0]/[12:8] -> uio_in / ui_in[7:3]; pin_out/pin_oe from uio_out/oe and uo_out[7:3]
    (the input-only pins' level register pin_out[12:8] reads 0, output-only pin_oe[17:13] is 1, as in
    pio_chip); irq0 = uo_out[2], irq1 = uo_out[1].
  * gl_fdebug: the FDEBUG flops (`u_chip.fdebug[*]`, kept by name) for `Chip.fdebug` peeks.
  * SRAM IMEM (imem_tech=sram2p): the netlist holds the PDK macro, whose array powers up X; the RTL build zeroes it
    from src/pio_imem_sram.sv (`PIO_SRAM_MODEL`, simulation only), so gl_top zeroes each macro's array the same way
    (an unprogrammed word that the engine fetches would otherwise be an X instruction, which silicon would not be
    either: it is undefined there, not X; the rigs never rely on it).
  * gl_levels: each engine's TX / RX FIFO level (the perf probe samples them every cycle), 8 bits per engine
    {rx[3:0], tx[3:0]}: the `u_eng.tx_level / rx_level` nets when synthesis kept them by name, else the bits of
    `u_chip.flevel_w` (the FLEVEL register, which is the same two nibbles).

The nets it needs are looked up in the netlist; a missing one raises with its name.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path


def nets(text: str) -> set[str]:
    return {a or b for a, b in re.findall(r"^\s*wire\s+(?:\\(\S+)\s*|(\w+)\s*);", text, re.M)}


def build(text: str) -> str:
    have = nets(text)

    def need(name: str) -> str:
        if name not in have:
            raise SystemExit(f"fw.gl_wrap: the netlist has no net {name!r}; the bus is not visible (was it synthesised "
                             "with a different host_spi / flattened differently?)")
        return "\\" + name + " " if re.search(r"[\[\].]", name) else name

    def level_bits(e: int, rx: bool) -> list[str]:
        """Netlist nets for the bits of engine e's tx/rx level, LSB first."""
        base = f"u_chip.g_eng[{e}].u_eng.{'rx' if rx else 'tx'}_level"
        out: list[str] = []
        while f"{base}[{len(out)}]" in have and len(out) < 4:
            out.append(f"{base}[{len(out)}]")
        if out:
            return out
        base = "u_chip.flevel_w"
        lo = 8 * e + (4 if rx else 0)
        while f"{base}[{lo + len(out)}]" in have and len(out) < 4:
            out.append(f"{base}[{lo + len(out)}]")
        return out

    aw = 10 if "bus_addr[9]" in have else 7
    nf = 0
    while f"u_chip.fdebug[{nf}]" in have:
        nf += 1
    if nf == 0:
        raise SystemExit("fw.gl_wrap: no u_chip.fdebug[*] flops in the netlist")
    L = ["`timescale 1ns / 1ps", "`default_nettype none", "",
         f"// generated by fw/gl_wrap.py from the netlist: AW={aw}, {nf} FDEBUG bits", "module gl_top (",
         "    input  wire        clk, rst_n,", "    input  wire        bus_we, bus_re,",
         f"    input  wire [{aw-1}:0] bus_addr,", "    input  wire [31:0] bus_wdata,",
         "    output wire [31:0] bus_rdata,", "    input  wire [17:0] pin_in,",
         "    output wire [17:0] pin_out, pin_oe,", "    output wire        irq0, irq1,",
         "    output wire [15:0] gl_fdebug,", "    output wire [31:0] gl_levels", ");",
         "  wire [7:0] uo_out, uio_out, uio_oe;",
         "  tt_um_protocol_emulator dut (",
         "      .ui_in({pin_in[12:8], 3'b000}),   // CSn low (host port selected, idle), SCK, MOSI low",
         "      .uo_out(uo_out), .uio_in(pin_in[7:0]), .uio_out(uio_out), .uio_oe(uio_oe),",
         "      .ena(1'b1), .clk(clk), .rst_n(rst_n));", "",
         "  assign pin_out = {uo_out[7:3], 5'b00000, uio_out};",
         "  assign pin_oe  = {5'b11111, 5'b00000, uio_oe};",
         "  assign irq0 = uo_out[2];", "  assign irq1 = uo_out[1];", "",
         "  // icarus evaluates the right side of a procedural `force` once, so re-force whenever a bus input moves",
         "  task apply_bus;", "  begin"]
    L.append(f"    force dut.{need('bus_we')} = bus_we;")
    L.append(f"    force dut.{need('bus_re')} = bus_re;")
    for i in range(aw):
        L.append(f"    force dut.{need(f'bus_addr[{i}]')} = bus_addr[{i}];")
    for i in range(32):
        L.append(f"    force dut.{need(f'bus_wdata[{i}]')} = bus_wdata[{i}];")
    L.append("  end")
    L.append("  endtask")
    L.append("  initial apply_bus;")
    L.append("  always @(bus_we or bus_re or bus_addr or bus_wdata) apply_bus;")
    L.append("")
    for i in range(31):
        L.append(f"  assign bus_rdata[{i}] = dut.{need(f'u_host.miso_sr_q[{i}]')};")
    L.append("  assign bus_rdata[31] = uo_out[0];   // miso_sr_q[31] is the MISO pin")
    for i in range(16):
        L.append(f"  assign gl_fdebug[{i}] = " + (f"dut.{need(f'u_chip.fdebug[{i}]')};" if i < nf else "1'b0;"))
    n_eng = 0
    for e in range(4):
        tx, rx = level_bits(e, False), level_bits(e, True)
        if not tx or not rx:
            break
        n_eng += 1
        for rxf, bits in ((False, tx), (True, rx)):
            for i in range(4):
                lhs = f"gl_levels[{8 * e + (4 if rxf else 0) + i}]"
                L.append(f"  assign {lhs} = " + (f"dut.{need(bits[i])};" if i < len(bits) else "1'b0;"))
    for i in range(8 * n_eng, 32):
        L.append(f"  assign gl_levels[{i}] = 1'b0;")
    if n_eng == 0:
        raise SystemExit("fw.gl_wrap: no FIFO level nets (u_eng.tx_level / u_chip.flevel_w) in the netlist")
    macros = re.findall(r"^\s*RM_IHPSG13_2P_64x22_c2_bm_bist\s+(\\\S+)\s", text, re.M)
    if macros:
        L += ["", "  integer w;", "  initial begin"]
        for m in macros:
            L += [f"    for (w = 0; w < 64; w = w + 1) dut.{m} .i_SRAM_2P_behavioral_bm_bist.mem_arr[w] = 22'd0;",
                  f"    dut.{m} .i_SRAM_2P_behavioral_bm_bist.dr_a_r = 22'd0;",
                  f"    dut.{m} .i_SRAM_2P_behavioral_bm_bist.dr_b_r = 22'd0;"]
        L.append("  end")
    L += ["", "endmodule", ""]
    return "\n".join(L)


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__)
        return 2
    out = Path(argv[1])
    out.parent.mkdir(parents=True, exist_ok=True)
    text = build(Path(argv[0]).read_text())
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
